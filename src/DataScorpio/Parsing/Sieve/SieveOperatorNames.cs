namespace DataScorpio.Parsing.Sieve;

/// <summary>
/// Normalized operator names produced by the Sieve compatibility parser.
/// </summary>
public static class SieveOperatorNames
{
    /// <summary>
    /// Equality.
    /// </summary>
    public const string Equal = "equals";

    /// <summary>
    /// Case-insensitive equality.
    /// </summary>
    public const string EqualInsensitive = "equalsInsensitive";

    /// <summary>
    /// Inequality.
    /// </summary>
    public const string NotEquals = "notEquals";

    /// <summary>
    /// Case-insensitive inequality.
    /// </summary>
    public const string NotEqualsInsensitive = "notEqualsInsensitive";

    /// <summary>
    /// Greater than.
    /// </summary>
    public const string GreaterThan = "greaterThan";

    /// <summary>
    /// Greater than or equal.
    /// </summary>
    public const string GreaterThanOrEqual = "greaterThanOrEqual";

    /// <summary>
    /// Less than.
    /// </summary>
    public const string LessThan = "lessThan";

    /// <summary>
    /// Less than or equal.
    /// </summary>
    public const string LessThanOrEqual = "lessThanOrEqual";

    /// <summary>
    /// String contains.
    /// </summary>
    public const string Contains = "contains";

    /// <summary>
    /// Case-insensitive string contains.
    /// </summary>
    public const string ContainsInsensitive = "containsInsensitive";

    /// <summary>
    /// String does not contain.
    /// </summary>
    public const string NotContains = "notContains";

    /// <summary>
    /// Case-insensitive string does not contain.
    /// </summary>
    public const string NotContainsInsensitive = "notContainsInsensitive";

    /// <summary>
    /// String starts with.
    /// </summary>
    public const string StartsWith = "startsWith";

    /// <summary>
    /// Case-insensitive string starts with.
    /// </summary>
    public const string StartsWithInsensitive = "startsWithInsensitive";

    /// <summary>
    /// String does not start with.
    /// </summary>
    public const string NotStartsWith = "notStartsWith";

    /// <summary>
    /// Case-insensitive string does not start with.
    /// </summary>
    public const string NotStartsWithInsensitive = "notStartsWithInsensitive";

    /// <summary>
    /// String ends with.
    /// </summary>
    public const string EndsWith = "endsWith";

    /// <summary>
    /// Case-insensitive string ends with.
    /// </summary>
    public const string EndsWithInsensitive = "endsWithInsensitive";

    /// <summary>
    /// String does not end with.
    /// </summary>
    public const string NotEndsWith = "notEndsWith";

    /// <summary>
    /// Case-insensitive string does not end with.
    /// </summary>
    public const string NotEndsWithInsensitive = "notEndsWithInsensitive";
}
